/**
 * Последние выбранные эмодзи.
 */
export function loadRecentEmoji(): string[] {
  if (typeof window === "undefined") return [];
  try {
    const raw = JSON.parse(localStorage.getItem(RECENT_KEY) || "[]");
    return Array.isArray(raw) ? raw.filter((x) => typeof x === "string").slice(0, 24) : [];
  } catch {
    return [];
  }
}

/**
 * Запомнить выбранный эмодзи в начале списка недавних.
 * @param emoji символ
 */
export function pushRecentEmoji(emoji: string): string[] {
  const next = [emoji, ...loadRecentEmoji().filter((x) => x !== emoji)].slice(0, 24);
  localStorage.setItem(RECENT_KEY, JSON.stringify(next));
  return next;
}
